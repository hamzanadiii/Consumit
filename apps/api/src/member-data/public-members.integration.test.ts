import pg from 'pg'
import { readFile } from 'node:fs/promises'
import { afterAll, beforeEach, describe, expect, it } from 'vitest'
import { publicProfileSchema } from '@consumit/contracts'
import { createDbClient } from '../db/client.ts'
import { createPublicMembers } from './public-members.ts'
import { createPostgresMemberData } from './postgres-member-data.ts'

const url = process.env.DATABASE_URL!
const control = new pg.Pool({ connectionString: url })
const db = createDbClient(url)
const service = createPublicMembers(db.prisma)
const personal = createPostgresMemberData(db.prisma)
beforeEach(async () => { await control.query('TRUNCATE "Member" CASCADE') })
afterAll(async () => { await db.close(); await control.end() })
async function member(username: string, visibility = 'public', displayName: string | null = null) {
  return db.prisma.member.create({ data: { email: `${username}@example.test`, profile: { create: { username, visibility, displayName, location: 'Secret location', bio: 'Published bio' } } } })
}

describe('public members on PostgreSQL', () => {
  it('projects published taste without private fields, honors aliases, visibility, lists and deletion', async () => {
    const owner = await member('published')
    await db.prisma.usernameAlias.create({ data: { username: 'previous_name', memberId: owner.id } })
    await db.prisma.favorite.create({ data: { memberId: owner.id, catalogKind: 'MOVIE', tmdbId: 550, position: 1, sourceKey: 'secret-import' } })
    await db.prisma.rating.create({ data: { memberId: owner.id, tmdbId: 550, value: 8, sourceKey: 'secret-import' } })
    await db.prisma.review.create({ data: { memberId: owner.id, tmdbId: 550, body: 'Published review', tags: ['private-tag'], sourceKey: 'secret-import' } })
    await db.prisma.diaryEntry.create({ data: { memberId: owner.id, tmdbId: 550, watchedOn: new Date() } })
    const list = await db.prisma.memberList.create({ data: { memberId: owner.id, slug: 'published-list', name: 'Published list', visibility: 'public' } })
    await db.prisma.memberList.create({ data: { memberId: owner.id, slug: 'private-list', name: 'Private list' } })
    const profile = publicProfileSchema.parse(await service.profile('previous_name'))
    expect(profile).toMatchObject({ canonicalUsername: 'published', statistics: { ratings: 1, reviews: 1, lists: 1 }, favorites: [{ id: 550, kind: 'movie', position: 1 }] })
    const serialized = JSON.stringify(profile)
    for (const field of ['location', 'diary', 'watched', 'watchlist', 'likes', 'tags', 'progress', 'email', 'sourceKey', 'origin', 'secret-import']) expect(serialized).not.toContain(field)
    expect(await service.collection('published', 'reviews', undefined, 20)).toMatchObject({ items: [{ body: 'Published review', id: 550 }] })
    expect(JSON.stringify(await service.collection('published', 'reviews', undefined, 20))).not.toContain('private-tag')
    expect(await service.collection('published', 'lists', undefined, 20)).toMatchObject({ items: [{ slug: list.slug }] })
    expect(await personal.list(list.slug)).not.toBeNull()
    expect(await personal.list('private-list')).toBeNull()
    await db.prisma.profile.update({ where: { memberId: owner.id }, data: { visibility: 'private' } })
    expect(await service.profile('previous_name')).toBeNull()
    expect(await service.collection('published', 'ratings', undefined, 20)).toBeNull()
    expect(await personal.list(list.slug)).toBeNull()
    expect(await personal.list(list.slug, owner.id)).not.toBeNull()
    await db.prisma.profile.update({ where: { memberId: owner.id }, data: { visibility: 'public' } })
    expect(await service.profile('published')).not.toBeNull()
    await db.prisma.member.update({ where: { id: owner.id }, data: { status: 'DELETED' } })
    expect(await service.profile('published')).toBeNull()
    expect(await service.profile('missing')).toBeNull()
    expect(await personal.list(list.slug)).toBeNull()
  })

  it('uses unique idempotent follows under concurrency, retains private relationships and filters public counts', async () => {
    const a = await member('follower_one'), b = await member('followed_two'), quiet = await member('quiet_member', 'private')
    await Promise.all(Array.from({ length: 10 }, () => service.follow(a.id, b.id, true)))
    expect(await db.prisma.follow.count()).toBe(1)
    await expect(service.follow(a.id, a.id, true)).rejects.toMatchObject({ code: 'BAD_REQUEST' })
    await expect(service.follow(a.id, quiet.id, true)).rejects.toMatchObject({ code: 'NOT_FOUND' })
    await db.prisma.profile.update({ where: { memberId: b.id }, data: { visibility: 'private' } })
    await service.follow(a.id, b.id, true)
    expect(await service.profile('follower_one')).toMatchObject({ social: { following: 0 } })
    expect(await service.collection('follower_one', 'following', undefined, 20)).toMatchObject({ items: [] })
    expect(await service.collection('follower_one', 'following', undefined, 20, a.id)).toMatchObject({ items: [{ id: b.id, private: true }] })
    expect(await db.prisma.follow.count()).toBe(1)
    await db.prisma.profile.update({ where: { memberId: b.id }, data: { visibility: 'public' } })
    expect(await service.profile('follower_one')).toMatchObject({ social: { following: 1 } })
    await Promise.all(Array.from({ length: 10 }, () => service.follow(a.id, b.id, false)))
    expect(await db.prisma.follow.count()).toBe(0)
    await Promise.all(Array.from({ length: 10 }, (_, index) => service.follow(a.id, b.id, index % 2 === 0)))
    expect(await db.prisma.follow.count()).toBeLessThanOrEqual(1)
    await service.follow(a.id, b.id, false)
    expect(await db.prisma.follow.count()).toBe(0)
    await db.prisma.member.update({ where: { id: b.id }, data: { status: 'DELETED' } })
    await expect(service.follow(a.id, b.id, true)).rejects.toMatchObject({ code: 'NOT_FOUND' })
  })

  it('finds substring names case-insensitively, ranks exact usernames first, pages without gaps, scopes cursors, and has trigram indexes', async () => {
    for (const name of ['cinema_aaa', 'cinema', 'cinema_bbb', 'other_name']) await member(name, 'public', 'Cinema Lover')
    await member('cinema_private', 'private')
    const deleted = await member('cinema_deleted')
    await db.prisma.member.update({ where: { id: deleted.id }, data: { status: 'DELETED' } })
    const first = await service.search('CINEMA', undefined, 2)
    expect(first.items[0]?.username).toBe('cinema')
    expect(first.nextCursor).toBeTruthy()
    const second = await service.search('cinema', first.nextCursor!, 2)
    expect(new Set([...first.items, ...second.items].map(row => row.username)).size).toBe(4)
    expect(second.nextCursor).toBeNull()
    await expect(service.search('lover', first.nextCursor!, 20)).rejects.toMatchObject({ code: 'BAD_REQUEST' })
    await expect(service.search('ci', undefined, 20)).rejects.toMatchObject({ code: 'BAD_REQUEST' })
    await expect(service.search('cinema', 'invalid', 20)).rejects.toMatchObject({ code: 'BAD_REQUEST' })
    expect((await service.search('ema_', undefined, 20)).items).toHaveLength(2)
    const indexes = await control.query("SELECT indexname FROM pg_indexes WHERE tablename = 'Profile' AND indexdef LIKE '%gin_trgm_ops%'")
    expect(indexes.rows).toHaveLength(2)
    await db.prisma.member.createMany({ data: Array.from({ length: 6000 }, (_, index) => ({ id: `search-fixture-${index}`, email: `unmatched${index}@example.test` })) })
    await db.prisma.profile.createMany({ data: Array.from({ length: 6000 }, (_, index) => ({ memberId: `search-fixture-${index}`, username: `unmatched${index}`, visibility: 'public' })) })
    await control.query(`SELECT gin_clean_pending_list('"Profile_public_username_trgm_idx"'::regclass)`)
    await control.query('ANALYZE "Profile"')
    await control.query('SET enable_seqscan = off; SET enable_indexscan = off; SET enable_indexonlyscan = off')
    const explain = await control.query(`EXPLAIN SELECT username FROM "Profile" WHERE visibility = 'public' AND username ILIKE '%cinema%'`)
    expect(JSON.stringify(explain.rows)).toContain('Profile_public_username_trgm_idx')
  }, 20000)

  it('paginates visitor collections without private list or review metadata and scopes each cursor', async () => {
    const owner = await member('paged_member')
    await member('another_member')
    await db.prisma.rating.createMany({ data: Array.from({ length: 6 }, (_, index) => ({ id: `rating-${index}`, memberId: owner.id, tmdbId: index + 1, value: 8, sourceKey: `private-import-${index}` })) })
    await db.prisma.review.createMany({ data: Array.from({ length: 6 }, (_, index) => ({ id: `review-${index}`, memberId: owner.id, tmdbId: index + 1, body: `Review ${index}`, tags: ['private-tag'], sourceKey: `private-import-${index}` })) })
    await db.prisma.memberList.createMany({ data: Array.from({ length: 6 }, (_, index) => ({ id: `list-${index}`, memberId: owner.id, slug: `paged-list-${index}`, name: `List ${index}`, visibility: index % 2 ? 'private' : 'public' })) })
    for (const collection of ['ratings', 'reviews', 'lists'] as const) {
      const first = await service.collection('paged_member', collection, undefined, 2)
      expect(first?.items).toHaveLength(2)
      expect(first?.nextCursor).toBeTruthy()
      const second = await service.collection('paged_member', collection, first!.nextCursor!, 2)
      const encoded = JSON.stringify([first, second])
      for (const field of ['sourceKey', 'origin', 'tags', 'private-tag']) expect(encoded).not.toContain(field)
      expect(second!.items.some(item => first!.items.some(previous => JSON.stringify(previous) === JSON.stringify(item)))).toBe(false)
      await expect(service.collection('another_member', collection, first!.nextCursor!, 2)).rejects.toMatchObject({ code: 'BAD_REQUEST' })
      await expect(service.collection('paged_member', collection === 'ratings' ? 'reviews' : 'ratings', first!.nextCursor!, 2)).rejects.toMatchObject({ code: 'BAD_REQUEST' })
      if (collection === 'lists') { expect(second?.items).toHaveLength(1); expect(second?.nextCursor).toBeNull() }
    }
  })

  it('normalizes legacy visibility exactly once while preserving member content and follows', async () => {
    const a = await member('legacy_one'), b = await member('legacy_two')
    await service.follow(a.id, b.id, true)
    await db.prisma.review.create({ data: { memberId: a.id, tmdbId: 550, body: 'Keep this review' } })
    await db.prisma.memberList.create({ data: { memberId: a.id, slug: 'legacy-list', name: 'Legacy list', visibility: 'public' } })
    const sql = await readFile(new URL('../../prisma/migrations/20261009170000_public_member_discovery/migration.sql', import.meta.url), 'utf8')
    await control.query(sql.split('CREATE EXTENSION')[0]!)
    expect(await db.prisma.profile.count({ where: { visibility: 'public' } })).toBe(0)
    expect(await db.prisma.memberList.count({ where: { visibility: 'public' } })).toBe(0)
    expect(await db.prisma.follow.count()).toBe(1)
    expect(await db.prisma.review.count()).toBe(1)
  })
})
