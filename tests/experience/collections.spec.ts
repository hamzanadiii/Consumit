test('phone creation stays usable across themes, blocks repeat submits, and safely retries a lost response', async ({ page, request }) => {
  await request.post(`${api}/__fixtures/reset`, { data: { preferences: { ...defaultExperiencePreferences(), guideVersion: GUIDE_VERSION, guideStatus: 'dismissed' } } })
  let loseResponse = true
  let markFirstResponseCommitted!: () => void
  let releaseFirstResponse!: () => void
  const firstResponseCommitted = new Promise<void>(resolve => { markFirstResponseCommitted = resolve })
  const firstResponseRelease = new Promise<void>(resolve => { releaseFirstResponse = resolve })
  const keys: string[] = []
  const createdSlugs: string[] = []
  await page.route(createRoute, async route => {
    keys.push(route.request().postDataJSON().idempotencyKey)
    const response = await route.fetch()
    const body = await response.json()
    createdSlugs.push(body.list.slug)
    if (loseResponse) {
      loseResponse = false
      markFirstResponseCommitted()
      await firstResponseRelease
      await route.fulfill({ status: 503, json: { error: { code: 'AUTH_STATE_UNAVAILABLE', message: 'The response was interrupted. Try again.', requestId: 'collection-fixture', retryable: true } } })
    } else await route.fulfill({ response })
  })
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/lists/new')
  const name = page.getByRole('textbox', { name: 'Name your collection' })
  const presentation = page.getByRole('combobox', { name: 'How should people explore it?' })
  const createButton = page.getByRole('button', { name: 'Build your collection' })
  const creationFields = page.getByRole('form', { name: 'New collection' }).locator('fieldset')
  await name.fill('A ranking for rainy nights')
  await presentation.selectOption('ranking')
  const themeSurface = page.locator('[data-filscreen-home]')
  await expect(themeSurface).toHaveAttribute('data-theme', 'dark')
  for (const [theme, capture] of [['dark', 'create-mobile-dark-320x700.png'], ['light', 'create-mobile-light-320x700.png']] as const) {
    if (theme === 'light') {
      await page.getByRole('button', { name: 'Open navigation' }).click()
      const mobileMenu = page.getByRole('dialog', { name: 'CONSUMIT' })
      await mobileMenu.getByRole('button', { name: 'Switch to light mode' }).click()
      await mobileMenu.getByRole('button', { name: 'Close navigation' }).click()
      await expect(themeSurface).toHaveAttribute('data-theme', 'light')
    }
    for (const [label, control] of [['Name', name], ['Presentation', presentation], ['Create', createButton]] as const) {
      expect.soft((await control.boundingBox())?.height, `${label} control height in ${theme} theme`).toBeGreaterThanOrEqual(44)
    }
    await mkdir('.impeccable/review/collection-journey', { recursive: true })
    await page.screenshot({ caret: 'initial', path: `.impeccable/review/collection-journey/${capture}`, fullPage: true })
    await expectWcag22Aa(page, `New collection form at 320×700 in ${theme} theme`)
  }
  await name.press('Enter')
  await firstResponseCommitted
  try {
    await expect(page.getByRole('button', { name: 'Creating…' })).toBeDisabled()
    await expect(name).toBeDisabled()
    await expect(presentation).toBeDisabled()
    await expect(creationFields).toHaveAttribute('aria-busy', 'true')
    const pendingActionOpacity = await page.getByRole('button', { name: 'Creating…' }).evaluate(button => {
      let opacity = 1
      let element: HTMLElement | null = button as HTMLElement
      while (element) {
        opacity *= Number.parseFloat(getComputedStyle(element).opacity)
        if (element.matches('main')) break
        element = element.parentElement
      }
      return opacity
    })
    expect(pendingActionOpacity, 'the pending create action should remain visibly legible while the form is locked').toBeGreaterThanOrEqual(0.9)
    await mkdir('.impeccable/review/collection-journey', { recursive: true })
    await page.screenshot({ caret: 'initial', path: '.impeccable/review/collection-journey/create-pending-mobile-light-320x700.png', fullPage: true })
    await expectWcag22Aa(page, 'Pending new collection form at 320×700 in light theme')
    // A second Enter during the held request must not create another collection.
    await page.keyboard.press('Enter')
    expect(keys).toHaveLength(1)
  } finally {
    releaseFirstResponse()
  }
  await expect(page.getByRole('main').getByRole('alert')).toContainText('The response was interrupted. Try again.')
  await expect(creationFields).toHaveAttribute('aria-busy', 'false')
  await expect(name).toBeEnabled()
  await expect(presentation).toBeEnabled()
  await expect(createButton).toBeEnabled()
  await expect(name).toHaveValue('A ranking for rainy nights')
  await expect(presentation).toHaveValue('ranking')
  await mkdir('.impeccable/review/collection-journey', { recursive: true })
  await page.screenshot({ caret: 'initial', path: '.impeccable/review/collection-journey/create-retry-mobile-light-320x700.png', fullPage: true })
  await expectWcag22Aa(page, 'Retryable new collection error at 320×700 in light theme')
  await name.press('Enter')
  await expect(page).toHaveURL(/\/lists\/quiet-evenings\/edit\?preset=ranking$/)
  await expect(page.getByRole('textbox', { name: 'Collection name', exact: true })).toHaveValue('A ranking for rainy nights')
  await expect(page.getByRole('combobox', { name: 'Visibility', exact: true })).toHaveValue('private')
  await expect(page.getByRole('combobox', { name: 'Presentation', exact: true })).toHaveValue('ranking')
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBe(keys[1])
  expect(createdSlugs).toEqual(['quiet-evenings', 'quiet-evenings'])
})

