async function expectWcag22Aa(page: Page, surface: string) {
  await page.addScriptTag({ content: axe.source })
  const violations = await page.evaluate(async () => {
    const axeApi = (window as unknown as Window & { axe: typeof axe }).axe
    return (await axeApi.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'] } })).violations.map(issue => ({ id: issue.id, targets: issue.nodes.map(node => node.target) }))
  })
  expect(violations, `${surface} should meet WCAG 2.2 AA`).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${surface} should fit the viewport`).toBe(true)
}

