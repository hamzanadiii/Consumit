test('episode selection preserves the fullscreen element, video and independent progress', async ({ page }) => {
  await page.goto('/watch/series/7?season=1&episode=1')
  const video = page.locator('video')
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState), { timeout: 30000 }).toBeGreaterThanOrEqual(2)
  await video.evaluate((element: HTMLVideoElement) => { element.pause(); element.currentTime = 8 })
  const originalVideo = await video.elementHandle()
  await page.getByRole('button', { name: 'Enter fullscreen', exact: true }).click()
  await expect(page.locator('[data-consumit-player]')).toHaveAttribute('data-fullscreen', 'true')
  await page.getByRole('button', { name: 'Episodes', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Episodes' })
  await drawer.getByRole('link', { name: /^Watch episode 2:/ }).click()
  await expect(page).toHaveURL(/episode=2/)
  await expect(page.locator('[data-consumit-player]')).toHaveAttribute('data-fullscreen', 'true')
  expect(await originalVideo!.evaluate(element => element === document.querySelector('video'))).toBe(true)
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentSrc)).toContain('episode=2')
  await page.getByRole('button', { name: 'Episodes', exact: true }).click()
  await drawer.getByRole('link', { name: /^Watch episode 1:/ }).click()
  await expect(page).toHaveURL(/episode=1/)
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeGreaterThanOrEqual(7)
  await page.goBack()
  await expect(page).toHaveURL(/episode=2/)
  await expect(page.locator('[data-consumit-player]')).toHaveAttribute('data-fullscreen', 'true')
})

test('season browsing does not navigate and closing returns to the deck', async ({ page }) => {
  await page.goto('/watch/series/7?season=1&episode=1')
  await expect(page.getByRole('button', { name: 'Episodes', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Episodes', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Episodes' })
  await drawer.getByRole('button', { name: /Season Season 1/ }).click()
  await page.getByRole('option', { name: 'Season 2', exact: true }).click()
  await expect(drawer.getByText('Season 2 · 2 episodes')).toBeVisible()
  await expect(page).toHaveURL(/season=1&episode=1/)
  await drawer.getByRole('searchbox', { name: 'Filter episodes' }).fill('nothing matches')
  await expect(drawer.getByText(/No episodes match/)).toBeVisible()
  await drawer.getByRole('button', { name: 'Close episodes' }).click()
  await expect(page.getByRole('searchbox', { name: 'Filter episodes' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Episodes', exact: true })).toBeFocused()
})

