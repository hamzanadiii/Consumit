import { expect, test } from '@playwright/test'

for (const theme of ['dark', 'light']) test(`${theme} account forms keep help, recovery, and long errors usable at every viewport`, async ({ page }, info) => {
  await page.addInitScript((value) => localStorage.setItem('consumit.home-theme', value), theme)
  await page.route('**/v1/me', route => route.fulfill({ json: { member: null } }))
  await page.route('**/v1/auth/login', route => route.fulfill({ status: 503, json: { error: {
    code: 'IDENTITY_NOT_CONFIGURED', requestId: 'fixture-auth-error', message: 'Sign-in is temporarily unavailable. Your details are still here. Please try again in a moment.', retryable: true,
  } } }))
  const response = await page.goto('/sign-in')
  expect(response!.headers()['x-content-type-options']).toBe('nosniff')
  expect(response!.headers()['content-security-policy']).toContain("base-uri 'self'")
  await page.getByLabel('Email', { exact: true }).fill('member@example.com')
  await page.getByLabel('Password', { exact: true }).fill('a-secure-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'temporarily unavailable' })).toBeVisible()
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue('member@example.com')
  const privacy = await page.getByText('Your account and library are private by default.').boundingBox()
  const help = await page.getByRole('link', { name: 'Need help?' }).boundingBox()
  expect(privacy).not.toBeNull()
  expect(help).not.toBeNull()
  expect(help!.height).toBeGreaterThanOrEqual(44)
  expect(privacy!.x + privacy!.width <= help!.x || privacy!.y + privacy!.height <= help!.y || help!.y + help!.height <= privacy!.y).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => document.fonts.ready.then(() => undefined))
  expect(await page.getByText('Your account and library are private by default.').evaluate((element) => getComputedStyle(element).fontFamily)).toContain('DejaVu Sans')
  await page.screenshot({ path: info.outputPath('sign-in-error.png'), fullPage: true })
  await page.goto('/sign-up')
  await expect(page.getByRole('heading', { name: 'Create your account.' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Need help?' })).toBeVisible()
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('maxlength', '128')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => document.fonts.ready.then(() => undefined))
  await page.screenshot({ path: info.outputPath('sign-up.png'), fullPage: true })
})
